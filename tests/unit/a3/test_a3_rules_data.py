"""A3 data layer (R-01): tools/harness/rules/*.json read as public data; no harness import. AC-03.1."""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[3]
RULES = REPO / "tools" / "harness" / "rules"
YAML = REPO / ".claude" / "research" / "scripts" / "r1_5_lint" / "lint_rules_full.yaml"

ENUM_APPLIES = {".gd", ".tscn", ".tres", "project.godot"}
GENERATED = {"fn", "prop", "sig", "enum", "class", "tscnclass", "color", "theme"}
LINT_REGEX_RULES = ["lint.det-global-rng", "lint.det-wallclock", "lint.det-time-scale", "lint.sim-node",
                    "lint.raw-keycode", "lint.g3-project"]
LINT_ALL = LINT_REGEX_RULES + ["lint.input-action", "lint.signal-name", "lint.indent-mixed", "lint.det-idle-tween",
                               "lint.det-idle-timer", "lint.det-idle-anim"]


def _load(name: str):
    p = RULES / name
    assert p.is_file(), f"{p} missing (generated by tools/harness/rules/build_lint_data.py, spec 03 section 2.4)"
    return json.loads(p.read_text())


def _rules() -> list:
    d = _load("lint_rules.json")
    return d["rules"]


def _yaml_blocks() -> dict:
    """{id: risk} from the r1_5 yaml without a yaml dependency (flat list of `- id:` blocks)."""
    out, cur = {}, None
    for ln in YAML.read_text().splitlines():
        m = re.match(r"^- id: (\S+)\s*$", ln)
        if m:
            cur = m.group(1)
            out[cur] = None
            continue
        m = re.match(r"^  false_positive_risk: (\w+)", ln)
        if m and cur:
            out[cur] = m.group(1)
    return out


def test_ac_03_1_schema_top_level():
    d = _load("lint_rules.json")
    assert d["schema"] == "harness.lint-rules/1"
    assert isinstance(d["godot"], str) and d["godot"]
    assert isinstance(d["rules"], list) and d["rules"]


def test_ac_03_1_every_rule_matches_item_schema():
    ids = set()
    for r in _rules():
        for k in ("id", "regex", "applies_to", "severity", "message", "hint", "family", "anchor", "scope", "risk"):
            assert k in r, f"rule {r.get('id')} lacks '{k}'"
        assert re.match(r"^[a-z0-9][a-zA-Z0-9._-]*$", r["id"]), r["id"]
        assert r["id"] not in ids, f"duplicate id {r['id']}"
        ids.add(r["id"])
        assert isinstance(r["regex"], str)
        assert isinstance(r["applies_to"], list) and r["applies_to"], r["id"]
        assert set(r["applies_to"]) <= ENUM_APPLIES, r["id"]
        assert r["severity"] in ("error", "warning", "info"), r["id"]
        assert isinstance(r["message"], str) and len(r["message"]) >= 1, r["id"]
        assert isinstance(r["hint"], str) and len(r["hint"]) >= 1, f"empty hint on {r['id']}"
        assert isinstance(r["family"], str), r["id"]
        assert r["anchor"] is None or isinstance(r["anchor"], str), r["id"]
        assert r["scope"] in ("all", "sim", "det"), r["id"]
        assert r["risk"] in ("low", "medium", "high", "n/a"), r["id"]
        if "demo_corpus_hits" in r:
            assert isinstance(r["demo_corpus_hits"], int)


def test_ac_03_1_r1_5_id_set_equals_yaml():
    yaml_ids = set(_yaml_blocks())
    assert len(yaml_ids) == 1213, f"yaml parse gave {len(yaml_ids)} ids (expected 1213)"
    data_ids = {r["id"] for r in _rules() if not r["id"].startswith("lint.")}
    assert data_ids == yaml_ids, (f"only in json: {sorted(data_ids - yaml_ids)[:5]}; "
                                  f"only in yaml: {sorted(yaml_ids - data_ids)[:5]}")


def test_ac_03_1_every_regex_compiles():
    bad = []
    for r in _rules():
        try:
            re.compile(r["regex"])
        except re.error as ex:
            bad.append((r["id"], str(ex)))
    assert not bad, bad[:5]


def test_ac_03_1_anchors_occur_literally_in_regex():
    bad = []
    for r in _rules():
        a = r["anchor"]
        if a is None:
            continue
        if not re.fullmatch(r"[A-Za-z_]\w*", a) or a not in r["regex"]:
            bad.append((r["id"], a))
    assert not bad, bad[:5]


def test_ac_03_1_anchor_and_family_conventions():
    for r in _rules():
        if r["id"].startswith("lint."):
            continue
        fam = r["id"].split("-", 1)[0]
        assert r["family"] == fam, f"{r['id']}: family {r['family']!r} != prefix {fam!r}"
        assert r["scope"] == "all", r["id"]
        if fam in ("syn", "tscn"):
            assert r["anchor"] is None, f"{r['id']}: hand rules carry no anchor"
        if fam in GENERATED:
            assert r["anchor"], f"{r['id']}: generated family needs an anchor"


def test_ac_03_1_severity_follows_risk():
    risk = _yaml_blocks()
    for r in _rules():
        if r["id"].startswith("lint."):
            assert r["risk"] == "n/a", r["id"]
            continue
        assert r["risk"] == risk[r["id"]], f"{r['id']}: risk {r['risk']} vs yaml {risk[r['id']]}"
        want = "error" if r["risk"] == "low" else "warning"
        assert r["severity"] == want, f"{r['id']}: risk {r['risk']} -> severity {r['severity']}, want {want}"


def test_ac_03_1_counts_by_risk_match_spike():
    rs = [r for r in _rules() if not r["id"].startswith("lint.")]
    assert len(rs) == 1213
    from collections import Counter
    c = Counter(r["risk"] for r in rs)
    assert (c["low"], c["medium"], c["high"]) == (1161, 13, 39)


def test_ac_03_1_lint_regex_rules_present():
    by_id = {r["id"]: r for r in _rules()}
    for rid in LINT_REGEX_RULES:
        assert rid in by_id, f"{rid} missing from lint_rules.json"
        r = by_id[rid]
        assert r["risk"] == "n/a", r
    assert by_id["lint.det-global-rng"]["scope"] == "det"
    assert by_id["lint.det-wallclock"]["scope"] == "det"
    assert by_id["lint.sim-node"]["scope"] == "sim" and by_id["lint.sim-node"]["severity"] == "error"
    assert by_id["lint.det-time-scale"]["scope"] == "all" and by_id["lint.det-time-scale"]["severity"] == "warning"
    assert by_id["lint.raw-keycode"]["severity"] == "warning"
    assert by_id["lint.g3-project"]["applies_to"] == ["project.godot"] and by_id["lint.g3-project"]["severity"] == "error"


def test_ac_03_1_lint_g3_project_regex_behaviour():
    r = {x["id"]: x for x in _rules()}["lint.g3-project"]
    rx = re.compile(r["regex"], re.M)
    assert rx.search("config_version=4\n") and rx.search("a\nconfig_version=3\nb")
    assert not rx.search("config_version=5\n")


def test_ac_03_1_det_global_rng_regex_behaviour():
    r = {x["id"]: x for x in _rules()}["lint.det-global-rng"]
    rx = re.compile(r["regex"])
    for yes in ("\treturn randf()", "\tx = randi_range(1, 6)", "\trandomize()", "\tseed(3)", "\ta.shuffle()", "\tb.pick_random()"):
        assert rx.search(yes), yes
    for no in ("\treturn rng.randf()", "func randf() -> float:", "\tself.rng.randi()"):
        assert not rx.search(no), no


